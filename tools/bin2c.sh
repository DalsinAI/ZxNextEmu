#!/bin/sh
# bin2c.sh file symbol > out.c : emit a const uint8_t array.
printf '/* Generated by tools/bin2c.sh from %s. */\n#include <stdint.h>\n\nconst uint8_t %s[] = {\n' "$(basename "$1")" "$2"
od -An -v -tx1 "$1" | sed 's/  */ /g; s/^ //; s/ $//' | awk '{ s = "   "; for (i = 1; i <= NF; i++) s = s " 0x" $i ","; print s }'
printf '};\n'
